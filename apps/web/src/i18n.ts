export type Locale = 'en' | 'ar';
export const DICTS: Record<Locale, Dict> = { en, ar };

export type TFn = (k: TKey, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): TFn {
  const d = DICTS[locale];
  return (k, vars) => {
    let s = d[k] ?? en[k] ?? k;
    if (vars) for (const [name, v] of Object.entries(vars)) s = s.split(`{${name}}`).join(String(v));
    return s;
  };
}

