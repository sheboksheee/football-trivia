export function modeCopy(key: ModeKey, locale: Locale): ModeCopy {
  if (locale === 'ar') return AR[key];
  const m = MODES[key];
  return { name: m.name.en, concept: m.concept, rules: m.rules, proposed: m.proposed, blockers: m.blockers };
}

export function modeName(key: ModeKey | 'tiebreak' | string, locale: Locale): string {
  if (key === 'tiebreak') return locale === 'ar' ? 'فاصل اللقب' : 'Championship tie-break';
  return modeCopy(key as ModeKey, locale).name;
}
